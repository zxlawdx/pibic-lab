#!/bin/sh
set -eu

# PIBIC Workspace 0.2 - atualiza SOMENTE o Workspace.
# Não altera sshd_config, porta 22, authorized_keys, IP, DNS ou ZeroTier.

if [ "$(id -u)" -ne 0 ]; then
    OWNER_USER="$(id -un)"
    if command -v doas >/dev/null 2>&1; then
        exec doas env PIBIC_WORKSPACE_OWNER="$OWNER_USER" sh "$0"
    elif command -v sudo >/dev/null 2>&1; then
        exec sudo env PIBIC_WORKSPACE_OWNER="$OWNER_USER" sh "$0"
    else
        echo "ERRO: execute a partir de um usuario normal com doas ou sudo."
        exit 1
    fi
fi

APP_USER="${PIBIC_WORKSPACE_OWNER:-${SUDO_USER:-${DOAS_USER:-}}}"
if [ -z "$APP_USER" ] || [ "$APP_USER" = "root" ]; then
    echo "ERRO: execute este instalador a partir do usuario normal que usara o Workspace."
    exit 1
fi
id "$APP_USER" >/dev/null 2>&1 || { echo "ERRO: usuario $APP_USER nao existe."; exit 1; }
APP_GROUP="$(id -gn "$APP_USER")"

FINAL_DIR=/opt/pibic-workspace
NEW_DIR=/opt/pibic-workspace.new
STAMP="$(date +%Y%m%d-%H%M%S)"
BACKUP_DIR="/opt/pibic-workspace.backup-$STAMP"
SERVICE_BACKUP="/tmp/pibic-workspace-service-$STAMP.bak"
HAD_NODE=0
HAD_NPM=0
command -v node >/dev/null 2>&1 && HAD_NODE=1
command -v npm >/dev/null 2>&1 && HAD_NPM=1

printf '\n==================================================\n'
printf 'PIBIC WORKSPACE 0.2 - UPGRADE\n'
printf '==================================================\n'
printf 'Usuario do terminal web: %s\n' "$APP_USER"
printf 'Bind: 127.0.0.1:8765\n'
printf 'SSH: sera mantido intacto\n'
printf 'ZeroTier: sera mantido intacto\n\n'

echo '[1/9] Dependencias...'
apk add --no-cache python3 py3-pip py3-virtualenv doas nodejs npm ca-certificates >/dev/null
update-ca-certificates >/dev/null 2>&1 || true

