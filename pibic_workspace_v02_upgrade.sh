#!/bin/sh
set -eu
CMD="${1:-}"
case "$CMD" in
  probe) echo ok ;;
  package-install|package-remove)
    KEY="${2:-}"; ACTION=add
    [ "$CMD" = package-remove ] && ACTION=del
    case "$KEY" in
      git) set -- git ;;
      python) [ "$ACTION" = add ] || { echo 'Python protegido' >&2; exit 3; }; set -- python3 py3-pip ;;
      docker) set -- docker ;;
      postgresql) set -- postgresql postgresql-client ;;
      nginx) set -- nginx ;;
      curl) set -- curl ;;
      wget) set -- wget ;;
      nano) set -- nano ;;
      vim) set -- vim ;;
      htop) set -- htop ;;
      nodejs) set -- nodejs ;;
      npm) set -- npm ;;
      *) echo 'Pacote nao permitido' >&2; exit 2 ;;
    esac
    if [ "$ACTION" = add ]; then exec apk add --no-cache "$@"; else exec apk del "$@"; fi
    ;;
  service)
    SERVICE="${2:-}"; ACTION="${3:-}"
    case "$SERVICE" in docker|nginx|postgresql) ;; *) echo 'Servico protegido ou nao permitido' >&2; exit 2;; esac
    case "$ACTION" in
      start|stop|restart) exec rc-service "$SERVICE" "$ACTION" ;;
      enable) exec rc-update add "$SERVICE" default ;;
      disable) exec rc-update del "$SERVICE" default ;;
      *) echo 'Acao invalida' >&2; exit 2 ;;
    esac
    ;;
  docker-info) command -v docker >/dev/null 2>&1 || exit 4; exec docker info ;;
  docker-list) command -v docker >/dev/null 2>&1 || exit 4; exec docker ps -a --format '{{json .}}' ;;
  docker-action)
    ACTION="${2:-}"; CONTAINER="${3:-}"
    case "$ACTION" in start|stop|restart) ;; *) echo 'Acao Docker invalida' >&2; exit 2;; esac
    case "$CONTAINER" in ''|*[!A-Za-z0-9_.-]*) echo 'Container invalido' >&2; exit 2;; esac
    exec docker "$ACTION" "$CONTAINER"
    ;;
  docker-logs)
    CONTAINER="${2:-}"
    case "$CONTAINER" in ''|*[!A-Za-z0-9_.-]*) echo 'Container invalido' >&2; exit 2;; esac
    exec docker logs --tail 200 "$CONTAINER"
    ;;
  *) echo 'Operacao nao permitida' >&2; exit 2 ;;
esac
